package com.vayro.app.factory.generators

import com.vayro.app.factory.model.AppBlueprint
import com.vayro.app.factory.model.DataEntitySpec
import java.io.File

/**
 * Generates SQL schemas, migrations, realistic mock seed data (JSON & SQL), and database initialization helpers.
 */
object DatabaseSetupEngine {

    fun generateDatabaseBundle(targetDir: File, blueprint: AppBlueprint): List<File> {
        val createdFiles = mutableListOf<File>()
        val dbDir = File(targetDir, "database").apply { mkdirs() }
        val migrationsDir = File(dbDir, "migrations").apply { mkdirs() }

        // 1. Initial schema DDL
        createdFiles += writeFile(migrationsDir, "001_initial_schema.sql", generateSchemaDdl(blueprint.entities))

        // 2. Seed data SQL
        createdFiles += writeFile(migrationsDir, "002_seed_data.sql", generateSeedSql(blueprint.entities))

        // 3. Mock JSON seed file
        createdFiles += writeFile(dbDir, "seed_data.json", generateSeedJson(blueprint.entities))

        // 4. Schema documentation
        createdFiles += writeFile(dbDir, "DATABASE_SCHEMA.md", generateSchemaDocs(blueprint))

        return createdFiles
    }

    fun generateSchemaDdl(entities: List<DataEntitySpec>): String {
        val sb = StringBuilder()
        sb.append("-- Vayro App Factory Database Schema\n")
        sb.append("-- Generated for offline SQLite / Room / Postgres compatibility\n\n")

        for (entity in entities) {
            sb.append("CREATE TABLE IF NOT EXISTS ${entity.tableName} (\n")
            val cols = entity.fields.map { f ->
                val sqlType = when (f.type) {
                    "Int" -> "INTEGER"
                    "Long" -> "INTEGER"
                    "Double" -> "REAL"
                    "Boolean" -> "INTEGER"
                    else -> "TEXT"
                }
                val pk = if (f.primaryKey) " PRIMARY KEY" else ""
                val nullable = if (!f.nullable && !f.primaryKey) " NOT NULL" else ""
                val default = if (f.defaultValue != null) " DEFAULT ${f.defaultValue}" else ""
                "    ${f.name} $sqlType$pk$nullable$default"
            }
            sb.append(cols.joinToString(",\n"))
            sb.append("\n);\n\n")

            // Index primary key / foreign keys / timestamps
            val timestampField = entity.fields.firstOrNull { it.name.contains("date", true) || it.name.contains("time", true) }
            if (timestampField != null) {
                sb.append("CREATE INDEX IF NOT EXISTS idx_${entity.tableName}_${timestampField.name} ON ${entity.tableName}(${timestampField.name});\n\n")
            }
        }

        return sb.toString()
    }

    fun generateSeedSql(entities: List<DataEntitySpec>): String {
        val sb = StringBuilder()
        sb.append("-- Mock seed data for development and testing\n\n")

        for (entity in entities) {
            val rows = generateMockRows(entity, count = 3)
            for (row in rows) {
                val colNames = row.keys.joinToString(", ")
                val values = row.values.joinToString(", ") { v ->
                    if (v is String) "'${v.replace("'", "''")}'" else "$v"
                }
                sb.append("INSERT INTO ${entity.tableName} ($colNames) VALUES ($values);\n")
            }
            sb.append("\n")
        }

        return sb.toString()
    }

    fun generateSeedJson(entities: List<DataEntitySpec>): String {
        val sb = StringBuilder()
        sb.append("{\n")
        val entityEntries = entities.map { entity ->
            val rows = generateMockRows(entity, count = 3)
            val rowStrings = rows.map { row ->
                val fields = row.entries.map { (k, v) ->
                    val formatted = when (v) {
                        is String -> "\"$v\""
                        is Boolean -> "$v"
                        else -> "$v"
                    }
                    "      \"$k\": $formatted"
                }.joinToString(",\n")
                "    {\n$fields\n    }"
            }.joinToString(",\n")
            "  \"${entity.tableName}\": [\n$rowStrings\n  ]"
        }
        sb.append(entityEntries.joinToString(",\n"))
        sb.append("\n}\n")
        return sb.toString()
    }

    private fun generateSchemaDocs(blueprint: AppBlueprint): String {
        val sb = StringBuilder()
        sb.append("# ${blueprint.name} - Database Schema Documentation\n\n")
        sb.append("Generated by Vayro App Factory.\n\n")

        for (entity in blueprint.entities) {
            sb.append("## Table: `${entity.tableName}` (${entity.name})\n\n")
            sb.append("| Column | Type | Primary Key | Nullable | Default |\n")
            sb.append("|---|---|---|---|---|\n")
            for (f in entity.fields) {
                sb.append("| `${f.name}` | ${f.type} | ${if (f.primaryKey) "✓" else ""} | ${if (f.nullable) "✓" else ""} | ${f.defaultValue ?: "-"} |\n")
            }
            sb.append("\n")
        }

        return sb.toString()
    }

    private fun generateMockRows(entity: DataEntitySpec, count: Int): List<Map<String, Any>> {
        val list = mutableListOf<Map<String, Any>>()
        for (i in 1..count) {
            val map = mutableMapOf<String, Any>()
            for (f in entity.fields) {
                val value: Any = when {
                    f.primaryKey -> "$i"
                    f.type == "Int" -> i * 10
                    f.type == "Long" -> System.currentTimeMillis() - (i * 86400000L)
                    f.type == "Double" -> (i * 19.99)
                    f.type == "Boolean" -> (i % 2 == 1)
                    f.name.contains("name", true) -> "${entity.name} #$i"
                    f.name.contains("title", true) -> "Sample ${entity.name} Item $i"
                    f.name.contains("email", true) -> "user$i@example.com"
                    f.name.contains("price", true) -> (i * 24.5)
                    f.name.contains("status", true) -> if (i == 1) "ACTIVE" else "PENDING"
                    f.name.contains("url", true) -> "https://picsum.photos/seed/$i/300/300"
                    else -> "Sample value for ${f.name} $i"
                }
                map[f.name] = value
            }
            list.add(map)
        }
        return list
    }

    private fun writeFile(dir: File, name: String, content: String): File {
        val file = File(dir, name)
        file.parentFile?.mkdirs()
        file.writeText(content.trimIndent())
        return file
    }
}
